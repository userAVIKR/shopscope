-- ShopScope analytics database: a fictional Indian e-commerce store.
-- Applied by database/seed.ts as shopscope_analytics_owner. Re-running drops and recreates everything.
--
-- Business rules (keep in sync with src/analytics/metrics.ts):
--   revenue          = SUM(order_items.quantity * order_items.unit_price), cancelled orders excluded
--   order count      = COUNT(DISTINCT orders.id), cancelled orders excluded
--   avg order value  = revenue / order count
-- This is gross item sales, not net accounting revenue: no taxes, discounts, shipping or refunds.

DROP TABLE IF EXISTS order_items, orders, products, categories, customers CASCADE;

CREATE TABLE customers (
  id         integer     PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name       text        NOT NULL CHECK (length(trim(name)) > 0),
  city       text        NOT NULL CHECK (length(trim(city)) > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE categories (
  id   integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name text    NOT NULL UNIQUE CHECK (length(trim(name)) > 0)
);

CREATE TABLE products (
  id          integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name        text          NOT NULL CHECK (length(trim(name)) > 0),
  category_id integer       NOT NULL REFERENCES categories (id),
  unit_price  numeric(10,2) NOT NULL CHECK (unit_price > 0),
  active      boolean       NOT NULL DEFAULT true
);

CREATE TABLE orders (
  id          integer PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  customer_id integer NOT NULL REFERENCES customers (id),
  status      text    NOT NULL CHECK (status IN ('pending', 'paid', 'shipped', 'delivered', 'cancelled')),
  order_date  date    NOT NULL
);

CREATE TABLE order_items (
  id         integer       PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  order_id   integer       NOT NULL REFERENCES orders (id) ON DELETE CASCADE,
  product_id integer       NOT NULL REFERENCES products (id),
  quantity   integer       NOT NULL CHECK (quantity > 0),
  unit_price numeric(10,2) NOT NULL CHECK (unit_price >= 0),
  UNIQUE (order_id, product_id)
);

-- Columns used in joins and filters
CREATE INDEX products_category_id_idx    ON products (category_id);
CREATE INDEX orders_customer_id_idx      ON orders (customer_id);
CREATE INDEX orders_order_date_idx       ON orders (order_date);
CREATE INDEX orders_status_idx           ON orders (status);
CREATE INDEX order_items_product_id_idx  ON order_items (product_id);
-- order_items (order_id) is covered by the UNIQUE (order_id, product_id) index.

COMMENT ON TABLE  customers             IS 'People who have an account with the store';
COMMENT ON COLUMN customers.city        IS 'Indian city the customer lives in';
COMMENT ON COLUMN customers.created_at  IS 'When the customer signed up';
COMMENT ON TABLE  categories            IS 'Product categories, e.g. Electronics, Grocery';
COMMENT ON TABLE  products              IS 'Items for sale';
COMMENT ON COLUMN products.unit_price   IS 'Current list price in INR';
COMMENT ON COLUMN products.active       IS 'false = discontinued, no longer sold';
COMMENT ON TABLE  orders                IS 'One checkout by one customer';
COMMENT ON COLUMN orders.status         IS 'pending, paid, shipped, delivered or cancelled. Cancelled orders never count towards revenue or order count';
COMMENT ON COLUMN orders.order_date     IS 'Date the order was placed';
COMMENT ON TABLE  order_items           IS 'Line items: which products, how many, at what price';
COMMENT ON COLUMN order_items.unit_price IS 'Price in INR per unit at the time of the order';

-- Default privileges already cover these, but grant explicitly so the reader works
-- even if the tables were created by a different role.
GRANT SELECT ON customers, categories, products, orders, order_items TO shopscope_reader;
